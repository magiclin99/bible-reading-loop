"""
test_refs.py — 引用解析器的回歸測試

每個案例都是實際踩過的坑。特別注意「本書」和「（二次）」兩類：它們連錯的
目標是存在的，語料驗證抓不到，只能靠這裡守住。

跑：  python test_refs.py
"""
import corpus
from refs import Parser, decode

vmax, _, _ = corpus.load()
P = Parser(vmax)

# (註文, host卷, host章, 期望[(連結文字, 目標, 註標)])
CASES = [
    # 「本書」＝本卷。不特判的話「書」是約書亞記的簡稱，會靜默連到約書亞記
    ("正如本書十三47～50撒網的比喻", "太", 13, [("本書十三47～50", "太13:47", None)]),
    ("本書四十9說到神來完成救贖", "賽", 40, [("本書四十9", "賽40:9", None)]),

    # 「者同」是譯詞註記，整條鏈抑制
    ("與本書十二13者同字根", "加", 2, []),
    ("直譯，開胎。12、15，三四19者同。", "創", 29, []),
    # 但「。後文同」不該抑制前面的鏈（中間隔了句號）
    ("意即兆頭。見十二38註2。後文同。", "太", 24,
     [("十二38註2", "太12:38", "2")]),

    # 分隔符「和」—— 漏認的話 52節 會退回本章（路13:52 不存在）
    ("十一29～32和42～52節這兩段話", "路", 13,
     [("十一29～32", "路11:29", None), ("42～52節", "路11:42", None)]),

    # 承接：14 必須接「加三」，不是 host
    ("（創二二17～18，加三16，14。）", "太", 1,
     [("創二二17～18", "創22:17", None), ("加三16", "加3:16", None), ("14", "加3:14", None)]),

    # 括號註記不含數字 → 插語，不可打斷鏈（否則 3 會被判成本章，且目標存在）
    ("（二1（二次）、3。）", "太", 5,
     [("二1", "太2:1", None), ("3", "太2:3", None)]),

    # ○ ＝ 0
    ("見詩一○四35註1。", "詩", 104, [("詩一○四35註1", "詩104:35", "1")]),

    # 裸「與註」無法判斷指哪個註 → 只連經節，「與註」留純文字
    ("見賽十四12～15與註，結二八12～19與註。", "結", 28,
     [("賽十四12～15", "賽14:12", None), ("結二八12～19", "結28:12", None)]),

    # 註N → 連結含註標
    ("見伯九5註1。", "伯", 9, [("伯九5註1", "伯9:5", "1")]),
    # 落單的「註2」不連
    ("羅一20與註1，註2；", "羅", 1, [("羅一20與註1", "羅1:20", "1")]),

    # 該章 = 最近提到的章，需跨句號記憶
    ("在徒十三34，保羅將確定的憐憫解釋為“大衛”。然後在該章35節，他指明", "賽", 55,
     [("徒十三34", "徒13:34", None), ("該章35節", "徒13:35", None)]),
    # 該章 的回指來源是「十章」這種無節數的寫法
    ("指十章的天使；見該章11註1。", "但", 11, [("該章11註1", "但10:11", "1")]),

    # 單章書：無章號
    ("猶11與註1。", "猶", 1, [("猶11與註1", "猶1:11", "1")]),
    ("（參猶14～15。）", "猶", 1, [("猶14～15", "猶1:14", None)]),

    # 見/參 只是提示詞，後面照裸節規則
    ("見26註6。", "創", 1, [("26註6", "創1:26", "6")]),

    # 半節標記
    ("羅七18上與註2。", "羅", 7, [("羅七18上與註2", "羅7:18", "2")]),
    ("二32中、39上大人像的銀胸膛", "但", 2,
     [("二32中", "但2:32", None), ("39上", "但2:39", None)]),

    # 本章
    ("從本章4節～二五46，主的話", "太", 24,
     [("本章4節～二五46", "太24:4", None)]),

    # 驗證擋下不存在的目標
    ("創一999", "創", 1, []),
]


def run():
    ok = bad = 0
    for body, ab, ch, want in CASES:
        got = [(body[l.start:l.end], f"{l.abbr}{l.ch}:{l.v}", l.note)
               for l in P.parse(body, ab, ch)]
        if got == want:
            ok += 1
        else:
            bad += 1
            print(f"FAIL  {body}")
            print(f"  期望 {want}")
            print(f"  實得 {got}")

    # 數字解碼
    for s, n in [("十", 10), ("十二", 12), ("二十", 20), ("二二", 22), ("一一九", 119),
                 ("一○四", 104), ("一一○", 110), ("一○○", 100), ("一四八", 148)]:
        if decode(s) != n:
            bad += 1
            print(f"FAIL  decode({s}) = {decode(s)}, 期望 {n}")
        else:
            ok += 1

    print(f"\n{ok} pass / {bad} fail")
    return bad == 0


if __name__ == "__main__":
    raise SystemExit(0 if run() else 1)
